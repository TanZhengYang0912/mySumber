  List<String> _equipmentTypeOptions(EquipmentImportCatalog catalog) {
    final values = catalog.models
        .where((model) => model.utilityType == _utilityType)
        .map((model) => model.equipmentType)
        .toSet()
        .toList();
    if (values.isEmpty) values.add(_equipmentType);
    return values;
  }

  List<String> _manufacturerOptions(EquipmentImportCatalog catalog) {
    final values = catalog.models
        .where((model) =>
            model.utilityType == _utilityType &&
            model.equipmentType == _equipmentType)
        .map((model) => model.manufacturer)
        .toSet()
        .toList();
    if (values.isEmpty) values.add(_manufacturer);
    return values;
  }

  List<ImportModel> _modelOptions(EquipmentImportCatalog catalog) {
    final models = catalog.models
        .where((model) =>
            model.utilityType == _utilityType &&
            model.equipmentType == _equipmentType &&
            model.manufacturer == _manufacturer)
        .toList();
    if (models.isEmpty) {
      models.insert(
        0,
        ImportModel(
          equipmentType: _equipmentType,
          utilityType: _utilityType,
          manufacturer: _manufacturer,
          model: _modelName,
          firmwareVersions: const [
            'Unknown',
            'Pending Verification',
            'Not Applicable',
          ],
        ),
      );
    }
    return models;
  }

  String _modelDisplayName(String model) =>
      model == 'Unspecified' ? 'Model not registered yet' : model;

  String _modelValueFromDisplay(String displayName) =>
      displayName == 'Model not registered yet' ? 'Unspecified' : displayName;

  void _applyGeneratedAssetTag(EquipmentImportCatalog catalog) {
    final current = normalizedAssetTag(_assetTagController.text);
    final lastGenerated = normalizedAssetTag(_lastAutoGeneratedAssetTag);
    if (_isEditing ||
        (current != null &&
            current != lastGenerated &&
            !current.startsWith('LEGACY-'))) {
      return;
    }
    final facility = _selectedFacility(catalog);
    if (facility == null) return;

    final generated = generateAvailableAssetTag(
      facility: facility,
      equipmentType: _equipmentType,
      existingNodes: context.read<DatasetState>().nodes,
    );
    _assetTagController.text = generated;
    _lastAutoGeneratedAssetTag = generated;
  }

  List<String> _firmwareOptions(
    EquipmentImportCatalog catalog,
    List<ImportModel> models,
  ) {
    final model = _firstWhereOrNull(models, (item) => item.model == _modelName);
    final versions = [...?model?.firmwareVersions];
    if (!versions.contains(_firmwareVersion)) {
      versions.insert(0, _firmwareVersion);
    }
    return versions;
  }

  void _syncModelSelection(EquipmentImportCatalog catalog) {
    final types = _equipmentTypeOptions(catalog);
    if (!types.contains(_equipmentType)) _equipmentType = types.first;
    final manufacturers = _manufacturerOptions(catalog);
    if (!manufacturers.contains(_manufacturer)) {
      _manufacturer = manufacturers.first;
    }
    final models = _modelOptions(catalog);
    if (!models.any((model) => model.model == _modelName)) {
      _modelName = models.first.model;
    }
    _syncFirmwareSelection(catalog);
  }

  void _syncFirmwareSelection(EquipmentImportCatalog catalog) {
    final versions = _firmwareOptions(catalog, _modelOptions(catalog));
    if (!versions.contains(_firmwareVersion)) _firmwareVersion = versions.first;
  }

  ImportFacility? _selectedFacility(EquipmentImportCatalog catalog) =>
      _firstWhereOrNull(
          catalog.facilities, (item) => item.code == _facilityCode);

  String _facilityDisplay(EquipmentImportCatalog catalog) =>
      _selectedFacility(catalog)?.name ?? 'Select a registered facility';

