class _CalendarPickerDialog extends StatefulWidget {
  final DateTime initialDate;
  const _CalendarPickerDialog({required this.initialDate});

  @override
  State<_CalendarPickerDialog> createState() => _CalendarPickerDialogState();
}

class _CalendarPickerDialogState extends State<_CalendarPickerDialog> {
  late DateTime _visibleMonth;
  late DateTime _selected;

  static const _weekdayLabels = ['S', 'M', 'T', 'W', 'T', 'F', 'S'];
  static const _monthNames = [
    'January',
    'February',
    'March',
    'April',
    'May',
    'June',
    'July',
    'August',
    'September',
    'October',
    'November',
    'December'
  ];

  @override
  void initState() {
    super.initState();
    _visibleMonth = DateTime(widget.initialDate.year, widget.initialDate.month);
    _selected = DateTime(widget.initialDate.year, widget.initialDate.month,
        widget.initialDate.day);
  }

  void _prevMonth() {
    setState(() {
      _visibleMonth = DateTime(_visibleMonth.year, _visibleMonth.month - 1);
    });
  }

  void _nextMonth() {
    setState(() {
      _visibleMonth = DateTime(_visibleMonth.year, _visibleMonth.month + 1);
    });
  }

  bool _sameDay(DateTime a, DateTime b) =>
      a.year == b.year && a.month == b.month && a.day == b.day;

  @override
  Widget build(BuildContext context) {
    final firstOfMonth = DateTime(_visibleMonth.year, _visibleMonth.month, 1);
    final leading = firstOfMonth.weekday % 7;
    final gridStart = firstOfMonth.subtract(Duration(days: leading));
    final today = DateTime.now();
    final todayNorm = DateTime(today.year, today.month, today.day);

    return Dialog(
      backgroundColor: Colors.white,
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(14)),
      insetPadding: const EdgeInsets.symmetric(horizontal: 40),
      child: Padding(
        padding: const EdgeInsets.fromLTRB(16, 14, 16, 12),
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            Row(
              children: [
                Row(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    Text(
                      '${_monthNames[_visibleMonth.month - 1]}, ${_visibleMonth.year}',
                      style: const TextStyle(
                        fontSize: 15,
                        fontWeight: FontWeight.w700,
                        color: AppColors.textPrimary,
                      ),
                    ),
                    const SizedBox(width: 2),
                    const Icon(Icons.arrow_drop_down,
                        size: 20, color: AppColors.textPrimary),
                  ],
                ),
                const Spacer(),
                InkWell(
                  onTap: _prevMonth,
                  borderRadius: BorderRadius.circular(20),
                  child: const Padding(
                    padding: EdgeInsets.all(4),
                    child: Icon(Icons.arrow_upward,
                        size: 20, color: AppColors.textPrimary),
                  ),
                ),
                const SizedBox(width: 4),
                InkWell(
                  onTap: _nextMonth,
                  borderRadius: BorderRadius.circular(20),
                  child: const Padding(
                    padding: EdgeInsets.all(4),
                    child: Icon(Icons.arrow_downward,
                        size: 20, color: AppColors.textPrimary),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 12),
            Row(
              children: _weekdayLabels
                  .map((d) => Expanded(
                        child: Center(
                          child: Text(
                            d,
                            style: const TextStyle(
                              fontSize: 12,
                              fontWeight: FontWeight.w700,
                              color: AppColors.textSecondary,
                            ),
                          ),
                        ),
                      ))
                  .toList(),
            ),
            const SizedBox(height: 6),
            for (int week = 0; week < 6; week++)
              Row(
                children: List.generate(7, (dow) {
                  final date = gridStart.add(Duration(days: week * 7 + dow));
                  final isCurrentMonth = date.month == _visibleMonth.month;
                  final isSelected = _sameDay(date, _selected);
                  final isToday = _sameDay(date, todayNorm);
                  return Expanded(
                    child: AspectRatio(
                      aspectRatio: 1,
                      child: InkWell(
                        onTap: () {
                          setState(() => _selected = date);
                          Navigator.of(context).pop(_CalendarResult(date));
                        },
                        borderRadius: BorderRadius.circular(6),
                        child: Container(
                          margin: const EdgeInsets.all(2),
                          decoration: isSelected
                              ? BoxDecoration(
                                  border: Border.all(
                                      color: AppColors.textPrimary, width: 1.4),
                                  borderRadius: BorderRadius.circular(6),
                                )
                              : null,
                          alignment: Alignment.center,
                          child: Text(
                            '${date.day}',
                            style: TextStyle(
                              fontSize: 13,
                              fontWeight: isToday || isSelected
                                  ? FontWeight.w800
                                  : FontWeight.w500,
                              color: !isCurrentMonth
                                  ? AppColors.textTertiary
                                  : AppColors.warning,
                            ),
                          ),
                        ),
                      ),
                    ),
                  );
                }),
              ),
            const SizedBox(height: 6),
            Row(
              children: [
                InkWell(
                  onTap: () =>
                      Navigator.of(context).pop(const _CalendarResult(null)),
                  borderRadius: BorderRadius.circular(6),
                  child: const Padding(
                    padding: EdgeInsets.symmetric(horizontal: 8, vertical: 6),
                    child: Text(
                      'Clear',
                      style: TextStyle(
                        fontSize: 14,
                        fontWeight: FontWeight.w600,
                        color: AppColors.textSecondary,
                      ),
                    ),
                  ),
                ),
                const Spacer(),
                InkWell(
                  onTap: () {
                    final now = DateTime.now();
                    Navigator.of(context).pop(_CalendarResult(
                        DateTime(now.year, now.month, now.day)));
                  },
                  borderRadius: BorderRadius.circular(6),
                  child: const Padding(
                    padding: EdgeInsets.symmetric(horizontal: 8, vertical: 6),
                    child: Text(
                      'Today',
                      style: TextStyle(
                        fontSize: 14,
                        fontWeight: FontWeight.w700,
                        color: AppColors.textPrimary,
                      ),
                    ),
                  ),
                ),
              ],
            ),
          ],
        ),
      ),
    );
  }
}
