class NodeFormScreen extends StatefulWidget {
  final EquipmentNode? node;
  final String? initialFacilityName;

  const NodeFormScreen({super.key, this.node, this.initialFacilityName});

  @override
  State<NodeFormScreen> createState() => _NodeFormScreenState();
}

class _NodeFormScreenState extends State<NodeFormScreen> {
  final _formKey = GlobalKey<FormState>();

  late final TextEditingController _assetTagController;
  late final TextEditingController _nameController;
  late final TextEditingController _serialController;
  late final TextEditingController _ipController;

  late String _equipmentType;
  late String _utilityType;
  late String _status;
  String? _facilityCode;
  late String _manufacturer;
  late String _modelName;
  late String _firmwareVersion;
  late String _ipAssignment;
  DateTime? _installationDate;
  DateTime? _lastMaintenanceDate;
  DateTime? _nextMaintenanceDate;

  final _lockedFormat = DateFormat('MMM d, y');
  final _editableFormat = DateFormat('dd/MM/yyyy');

  static const _utilityTypes = ['Water', 'Electricity'];
  static const _statuses = ['Active', 'Warning', 'Critical', 'Maintenance'];
  static const _ipAssignments = ['Static', 'DHCP', 'Not Assigned'];

  bool _catalogInitialized = false;
  bool _isSaving = false;
  String? _lastAutoGeneratedAssetTag;

  bool get _isEditing => widget.node != null;

  @override
  void initState() {
    super.initState();
    final existing = widget.node;
    _assetTagController = TextEditingController(
      text: existing?.assetTag ?? '',
    );
    _nameController = TextEditingController(
      text: existing == null ? '' : equipmentDisplayName(existing),
    );
    _serialController =
        TextEditingController(text: existing?.serialNumber ?? '');
    _ipController = TextEditingController(text: existing?.ipAddress ?? '');

    _equipmentType = existing?.equipmentType ??
        (existing == null
            ? 'Main Water Pump'
            : equipmentTypeFromDisplayName(existing.nodeName));
    _utilityType = existing?.utilityType ?? 'Water';
    final rawStatus = existing?.status ?? 'Active';
    _status = _statuses.contains(rawStatus) ? rawStatus : 'Active';
    _facilityCode = existing?.facilityCode;
    _manufacturer = existing?.manufacturer ?? 'Grundfos';
    _modelName = existing?.modelName ?? 'Unspecified';
    _firmwareVersion = existing?.firmwareVersion ?? 'Unknown';
    _ipAssignment = _ipAssignments.contains(existing?.ipAssignment)
        ? existing!.ipAssignment
        : (existing?.ipAddress == null ? 'Not Assigned' : 'Static');

    final now = DateTime.now();
    _installationDate = existing?.installationDate ?? now;
    _lastMaintenanceDate = existing?.lastMaintenanceDate ?? now;
    _nextMaintenanceDate = existing?.nextMaintenanceDate;
  }

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    if (_catalogInitialized) return;
    final catalog = context.read<DatasetState>().importCatalog;
    final current = widget.node;
    if (_facilityCode == null && current?.facilityName != null) {
      _facilityCode = catalog.facilities
          .where((facility) => facility.name == current!.facilityName)
          .map((facility) => facility.code)
          .firstOrNull;
    }
    if (_facilityCode == null && widget.initialFacilityName != null) {
      _facilityCode = catalog.facilities
          .where((facility) => facility.name == widget.initialFacilityName)
          .map((facility) => facility.code)
          .firstOrNull;
    }
    final model = catalog.modelFor(
      equipmentType: _equipmentType,
      utilityType: _utilityType,
      manufacturer: _manufacturer,
      model: _modelName,
    );
    if (model != null) {
      _equipmentType = model.equipmentType;
      _utilityType = model.utilityType;
      _manufacturer = model.manufacturer;
      _modelName = model.model;
      if (!model.firmwareVersions.contains(_firmwareVersion)) {
        _firmwareVersion = model.firmwareVersions.first;
      }
    }
    _syncModelSelection(catalog);
    _applyGeneratedAssetTag(catalog);
    _catalogInitialized = true;
  }

  @override
  void dispose() {
    _assetTagController.dispose();
    _nameController.dispose();
    _serialController.dispose();
    _ipController.dispose();
    super.dispose();
  }

  Future<void> _save() async {
    if (_isSaving) return;
    final catalog = context.read<DatasetState>().importCatalog;
    _applyGeneratedAssetTag(catalog);
    if (!_formKey.currentState!.validate()) return;
    final facility = catalog.facilities
        .where((item) => item.code == _facilityCode)
        .firstOrNull;
    final model = catalog.modelFor(
      equipmentType: _equipmentType,
      utilityType: _utilityType,
      manufacturer: _manufacturer,
      model: _modelName,
    );
    if (facility == null || model == null) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content:
              Text('Choose a facility and a registered model before saving.'),
          backgroundColor: AppColors.critical,
        ),
      );
      return;
    }
    final assetTag = _assetTagController.text.trim().toUpperCase();
    final displayName = _nameController.text.trim();
    final node = EquipmentNode(
      nodeId: widget.node?.nodeId,
      assetTag: assetTag,
      nodeName:
          displayName.isEmpty ? '$_equipmentType · $assetTag' : displayName,
      equipmentType: _equipmentType,
      utilityType: _utilityType,
      status: _status,
      zoneId: facility.state,
      facilityId: facility.facilityId ?? widget.node?.facilityId,
      facilityCode: facility.code,
      facilityName: facility.name,
      facilityCity: facility.city,
      modelId: model.modelId ?? widget.node?.modelId,
      modelName: model.model,
      serialNumber: _serialController.text.trim().isEmpty
          ? null
          : _serialController.text.trim(),
      manufacturer: model.manufacturer,
      manufacturerId: model.manufacturerId ?? widget.node?.manufacturerId,
      firmwareId:
          model.firmwareIds[_firmwareVersion] ?? widget.node?.firmwareId,
      firmwareVersion: _firmwareVersion,
      ipAssignment: _ipAssignment,
      ipAddress: _ipAssignment == 'Static' ? _ipController.text.trim() : null,
      installationDate: _installationDate,
      lastMaintenanceDate: _lastMaintenanceDate,
      nextMaintenanceDate: _nextMaintenanceDate,
    );
    final messenger = ScaffoldMessenger.of(context);
    setState(() => _isSaving = true);
    try {
      await context.read<DatasetState>().addOrUpdateNode(node);
      if (!mounted) return;
      Navigator.of(context).pop(true);
    } catch (error) {
      if (!mounted) return;
      setState(() => _isSaving = false);
      messenger.showSnackBar(
        SnackBar(
          content: Text('Could not save deployment: $error'),
          backgroundColor: AppColors.critical,
        ),
      );
    }
  }

  Future<void> _pickNextMaintenanceDate() async {
    final result = await showDialog<_CalendarResult>(
      context: context,
      barrierColor: Colors.black54,
      builder: (ctx) => _CalendarPickerDialog(
        initialDate: _nextMaintenanceDate ?? DateTime.now(),
      ),
    );
    if (result != null) {
      setState(() => _nextMaintenanceDate = result.date);
    }
  }

